"""FastAPI Application for LegalBot — Multi-Agent Legal Assistant.

Provides:
- GET /: Serves the frontend single-page interface.
- POST /ask: Coordinates the three Agno agents to analyze, research, and review legal queries.
- GET /health: Reports the health status, model, and active agents.
"""

import asyncio
import logging
from pathlib import Path
from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles

from app import config
from app.agents.legal_team import AGENT_NAMES, run_legal_workflow
from app.schemas import HealthResponse, LegalBotResponse, LegalQuestionRequest

# Configure logging without exposing sensitive data
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("legalbot")

BASE_DIR = Path(__file__).resolve().parent
STATIC_DIR = BASE_DIR / "static"

app = FastAPI(
    title="LegalBot — Multi-Agent Legal Assistant",
    description="Collaborative multi-agent legal guidance powered by Agno and Groq.",
    version="1.0.0",
)

# Enable CORS for local testing and browser clients
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Mount static assets
if STATIC_DIR.exists():
    app.mount("/static", StaticFiles(directory=str(STATIC_DIR)), name="static")


@app.get("/", summary="Serve LegalBot Frontend", response_class=FileResponse)
async def serve_frontend():
    """Serve the single-page HTML application."""
    index_file = STATIC_DIR / "index.html"
    if not index_file.exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Frontend index.html file not found in static assets directory.",
        )
    return FileResponse(str(index_file), media_type="text/html")


@app.get("/health", summary="Health Check", response_model=HealthResponse)
async def health_check() -> HealthResponse:
    """Report application health, model name, and multi-agent system readiness.

    Ensures API keys are never exposed in responses or logs.
    """
    return HealthResponse(
        status="healthy",
        app_name="LegalBot — Multi-Agent Legal Assistant",
        groq_configured=config.is_provider_configured(),
        model=config.get_active_model_name(),
        agents=AGENT_NAMES,
    )


@app.post("/ask", summary="Ask Legal Question", response_model=LegalBotResponse)
async def ask_question(request: LegalQuestionRequest) -> LegalBotResponse:
    """Process a user question through the three collaborating Agno agents.

    Workflow:
    1. Validate question input.
    2. Check API key readiness (Google Gemini or Groq).
    3. Execute the coordinated Agno team (Analyzer -> Researcher -> Reviewer)
       with request timeout enforcement.
    4. Return verified answer, consulted sources, and legal disclaimer.
    """
    if not config.is_provider_configured():
        logger.warning("Invocation rejected: No valid API key configured in environment.")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "API key is not configured. Please add your GEMINI_API_KEY (from https://aistudio.google.com/apikey) "
                "or GROQ_API_KEY (from https://console.groq.com/keys) to the .env file."
            ),
        )

    logger.info("Processing legal inquiry (length=%d characters)...", len(request.question))

    try:
        # Run synchronous Agno Team inside worker thread with timeout protection
        workflow_task = asyncio.to_thread(run_legal_workflow, request.question)
        result = await asyncio.wait_for(workflow_task, timeout=config.REQUEST_TIMEOUT)

        return LegalBotResponse(
            status="success",
            question=request.question,
            answer=result.get("answer", "No answer generated by the agent team."),
            sources=result.get("sources", []),
            disclaimer=config.LEGAL_DISCLAIMER,
        )

    except asyncio.TimeoutError:
        logger.error("Legal research workflow timed out after %d seconds.", config.REQUEST_TIMEOUT)
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail=f"Analysis timed out after {config.REQUEST_TIMEOUT} seconds. Please try a simpler question.",
        )

    except Exception as exc:
        error_msg = str(exc)
        # Prevent any potential key leaks in error messages
        if config.GROQ_API_KEY and config.GROQ_API_KEY in error_msg:
            error_msg = error_msg.replace(config.GROQ_API_KEY, "[REDACTED]")

        logger.exception("Error occurred during multi-agent reasoning: %s", error_msg)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"An error occurred while coordinating the legal agents: {error_msg}",
        )


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(
        "app.main:app",
        host=config.HOST,
        port=config.PORT,
        reload=True,
    )
